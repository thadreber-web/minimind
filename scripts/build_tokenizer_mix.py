"""Build a prose + dialogue + code text mix for tokenizer training, plus per-domain held-out sets.

Writes {"text": ...} jsonl (the format trainer/train_tokenizer.py reads) and a manifest.
Run inside the container from /workspace/minimind. Budgets are in characters.
"""
import argparse
import json
import os
import random
import re

from datasets import load_dataset

PERMISSIVE = {'mit', 'apache-2.0', 'bsd-3-clause', 'bsd-2-clause', 'isc', 'unlicense', 'cc0-1.0'}
HELDOUT_N = 200
CJK = re.compile(r'[\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]')
REJECTED = {'cjk': 0}


def no_cjk(rows, enabled):
    """Drop texts containing Chinese/Japanese/Korean characters when enabled."""
    for t in rows:
        if enabled and t and CJK.search(t):
            REJECTED['cjk'] += 1
            continue
        yield t


def take(rows, budget, heldout_n=0):
    """Collect texts until `budget` characters; then collect `heldout_n` more as held-out."""
    train, held, chars = [], [], 0
    for t in rows:
        if not t:
            continue
        if chars < budget:
            train.append(t)
            chars += len(t)
        elif len(held) < heldout_n:
            held.append(t)
        else:
            break
    return train, held, chars


def from_jsonl(path, seed=None):
    """Yield texts in file order, or in a seeded random order when seed is given."""
    texts = [json.loads(l)['text'] for l in open(path, encoding='utf-8')]
    if seed is not None:
        random.Random(seed).shuffle(texts)
    yield from texts


def smoltalk(split, seed):
    ds = load_dataset('HuggingFaceTB/smol-smoltalk', split=split, streaming=True)
    if split == 'train':
        ds = ds.shuffle(seed=seed, buffer_size=20000)
    for r in ds:
        # same as trainer/train_tokenizer.py: contents joined by newline, no role names
        yield '\n'.join(m['content'] for m in r['messages'] if m.get('content'))


def codeqa(seed):
    glaive = load_dataset('glaiveai/glaive-code-assistant', split='train').shuffle(seed=seed)
    alpaca = load_dataset('sahil2801/CodeAlpaca-20k', split='train').shuffle(seed=seed)
    for r in glaive:
        yield '\n'.join(x for x in (r['question'], r['answer']) if x and x.strip())
    for r in alpaca:
        yield '\n'.join(x for x in (r['instruction'], r.get('input'), r['output']) if x and x.strip())


def pyfiles(files, seed, skip_first=0):
    ds = load_dataset('codeparrot/codeparrot-clean', data_files=files, split='train', streaming=True)
    ds = ds.shuffle(seed=seed, buffer_size=5000)
    for r in ds:
        c = r['content']
        if r['license'] in PERMISSIVE and not r['autogenerated'] in (True, 'True') and 200 <= len(c) <= 20000:
            yield c


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--out', required=True, help='mix jsonl')
    p.add_argument('--outdir', required=True, help='held-out sets and manifest go here')
    p.add_argument('--cosmopedia', default='dataset/tok_cosmopedia.jsonl')
    p.add_argument('--tinystories', default='dataset/tok_tinystories.jsonl')
    p.add_argument('--prose-cosmo-mb', type=float, default=145)
    p.add_argument('--prose-tiny-mb', type=float, default=20)
    p.add_argument('--dialogue-mb', type=float, default=30)
    p.add_argument('--codeqa-mb', type=float, default=36)
    p.add_argument('--pyfiles-mb', type=float, default=69)
    p.add_argument('--seed', type=int, default=0)
    p.add_argument('--shuffle-prose', action='store_true', help='sample prose documents in random order instead of file order')
    p.add_argument('--drop-cjk', action='store_true', help='drop every document containing Chinese/Japanese/Korean characters')
    args = p.parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    mb = 1_000_000

    py_train_files = [f'file-0000000000{n:02d}.json.gz' for n in (1, 12, 24, 36, 48)]
    py_held_files = ['file-000000000054.json.gz']
    domains = {}  # name -> (texts, chars, heldout)
    domains['prose_cosmopedia'] = take(no_cjk(from_jsonl(args.cosmopedia, args.seed if args.shuffle_prose else None), args.drop_cjk), args.prose_cosmo_mb * mb)
    domains['prose_tinystories'] = take(no_cjk(from_jsonl(args.tinystories, args.seed if args.shuffle_prose else None), args.drop_cjk), args.prose_tiny_mb * mb)
    t, _, c = take(no_cjk(smoltalk('train', args.seed), args.drop_cjk), args.dialogue_mb * mb)
    domains['dialogue_smoltalk'] = (t, [], c)
    domains['code_qa'] = take(no_cjk(codeqa(args.seed), args.drop_cjk), args.codeqa_mb * mb, HELDOUT_N)
    domains['code_python_files'] = take(no_cjk(pyfiles(py_train_files, args.seed), args.drop_cjk), args.pyfiles_mb * mb)

    held = {
        'dialogue_smoltalk': list(take(no_cjk(smoltalk('test', args.seed), args.drop_cjk), 0, HELDOUT_N)[1]),
        'code_qa': domains['code_qa'][1],
        'code_python_files': list(take(no_cjk(pyfiles(py_held_files, args.seed), args.drop_cjk), 0, HELDOUT_N)[1]),
    }
    for name, texts in held.items():
        with open(os.path.join(args.outdir, f'heldout_{name}.jsonl'), 'w', encoding='utf-8') as f:
            for t in texts:
                f.write(json.dumps({'text': t}, ensure_ascii=False) + '\n')

    docs = [(name, t) for name, (texts, _, _) in domains.items() for t in texts]
    random.Random(args.seed).shuffle(docs)
    total = sum(len(t) for _, t in docs)
    with open(args.out, 'w', encoding='utf-8') as f:
        for _, t in docs:
            f.write(json.dumps({'text': t}, ensure_ascii=False) + '\n')

    manifest = {
        'out': args.out, 'seed': args.seed, 'docs': len(docs), 'chars': total,
        'domains': {n: {'docs': len(v[0]), 'chars': v[2], 'share': round(v[2] / total, 3)} for n, v in domains.items()},
        'heldout_docs': {n: len(v) for n, v in held.items()},
        'python_files_used': py_train_files, 'python_heldout_files': py_held_files,
        'python_licenses_kept': sorted(PERMISSIVE),
        'shuffle_prose': args.shuffle_prose, 'drop_cjk': args.drop_cjk, 'rejected_for_cjk': REJECTED['cjk'],
    }
    json.dump(manifest, open(os.path.join(args.outdir, 'manifest.json'), 'w'), indent=2)
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
