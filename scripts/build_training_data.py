"""Build English pretraining and SFT files for MiniMind from public datasets.

pretrain: documents from several sources are filtered (no CJK text, exact duplicates removed), split at line/sentence
          boundaries so no piece exceeds the context, then packed into chunks of at most (max_seq_len - 2) tokens joined by
          "<|im_end|><|im_start|>". PretrainDataset adds bos/eos itself and truncates/pads each row, so packing avoids
          wasted padding and truncated documents. Output rows: {"text": ...}.
sft:      conversations from several sources, filtered (no CJK text, must end with an assistant turn, exact duplicates
          removed, chat-template length <= --max-tokens). Output rows: {"conversations": [{"role", "content"}, ...]}.

Run inside the container from /workspace/minimind. Token counts use the tokenizer in model/.
"""
import argparse
import hashlib
import json
import os
import random
import re
from multiprocessing import Pool

from datasets import load_dataset
from tokenizers import Tokenizer

CJK = re.compile(r'[一-鿿぀-ヿ가-힯]')
PERMISSIVE = {'mit', 'apache-2.0', 'bsd-3-clause', 'bsd-2-clause', 'isc', 'unlicense', 'cc0-1.0'}
SEP = '<|im_end|><|im_start|>'
STATS = {'cjk_dropped': 0, 'duplicates_dropped': 0, 'empty_dropped': 0}


def md5(s):
    return hashlib.md5(s.encode('utf-8')).hexdigest()


def collect(rows, budget_chars, seen):
    """Take texts until the character budget is reached; skip empty, CJK and exact-duplicate texts."""
    out, chars = [], 0
    for t in rows:
        if not t or not t.strip():
            STATS['empty_dropped'] += 1
        elif CJK.search(t):
            STATS['cjk_dropped'] += 1
        elif md5(t) in seen:
            STATS['duplicates_dropped'] += 1
        else:
            seen.add(md5(t))
            out.append(t)
            chars += len(t)
            if chars >= budget_chars:
                break
    return out, chars


# ---------------- pretraining sources ----------------
def src_cosmopedia(path, seed):
    texts = [json.loads(l)['text'] for l in open(path, encoding='utf-8')]
    random.Random(seed).shuffle(texts)
    yield from texts


def src_tinystories(seed):
    for r in load_dataset('roneneldan/TinyStories', split='train').shuffle(seed=seed):
        yield r['text']


def src_fineweb(seed):
    ds = load_dataset('HuggingFaceFW/fineweb-edu', name='sample-10BT', split='train', streaming=True)
    for r in ds.shuffle(seed=seed, buffer_size=10000):
        yield r['text']


def src_python(seed):
    files = [f'file-0000000000{n:02d}.json.gz' for n in range(2, 54, 5)]
    ds = load_dataset('codeparrot/codeparrot-clean', data_files=files, split='train', streaming=True)
    for r in ds.shuffle(seed=seed, buffer_size=5000):
        c = r['content']
        if r['license'] in PERMISSIVE and r['autogenerated'] not in (True, 'True') and 200 <= len(c) <= 20000:
            yield c


def count_tokens(tok, texts, batch=20000):
    out = []
    for i in range(0, len(texts), batch):
        out.extend(len(e.ids) for e in tok.encode_batch(texts[i:i + batch]))
    return out


def split_text(text, ntok, budget):
    """Cut text into pieces of roughly <= budget tokens at newline / sentence boundaries."""
    if ntok <= budget:
        return [text]
    size = max(200, int(len(text) * budget / ntok * 0.9))
    pieces, i = [], 0
    while i < len(text):
        j = min(len(text), i + size)
        if j < len(text):
            cut = text.rfind('\n', i + size // 2, j)
            if cut == -1:
                c2 = text.rfind('. ', i + size // 2, j)
                cut = c2 + 1 if c2 != -1 else j - 1
            j = cut + 1
        pieces.append(text[i:j])
        i = j
    return [p for p in pieces if p.strip()]


def build_pretrain(args):
    tok = Tokenizer.from_file(args.tokenizer)
    budget = args.max_seq_len - 2
    seen = set()
    plan = [('cosmopedia', src_cosmopedia(args.cosmopedia, args.seed), args.cosmopedia_mb),
            ('tinystories', src_tinystories(args.seed), args.tinystories_mb),
            ('fineweb_edu', src_fineweb(args.seed), args.fineweb_mb),
            ('python_code', src_python(args.seed), args.python_mb)]
    pieces = []  # (source, text, tokens)
    manifest = {'sources': {}}
    for name, gen, mb in plan:
        texts, chars = collect(gen, mb * 1_000_000, seen)
        ntoks = count_tokens(tok, texts)
        n_pieces = 0
        for t, n in zip(texts, ntoks):
            parts = split_text(t, n, budget)
            counts = [n] if len(parts) == 1 else count_tokens(tok, parts)
            for p, c in zip(parts, counts):
                while c > budget:  # still too long: halve it
                    mid = len(p) // 2
                    cut = p.rfind('\n', 0, mid + 1)
                    cut = cut + 1 if cut > 0 else mid
                    a, b = p[:cut], p[cut:]
                    pieces.append((name, a, len(tok.encode(a).ids)))
                    p, c = b, len(tok.encode(b).ids)
                pieces.append((name, p, c))
                n_pieces += 1
        manifest['sources'][name] = {'docs': len(texts), 'chars': chars, 'source_tokens': sum(ntoks), 'pieces': n_pieces}
        print(name, manifest['sources'][name], flush=True)

    random.Random(args.seed).shuffle(pieces)
    # best-fit packing over up to 64 open rows; the fullest row is flushed when a 65th would be needed
    chunks, open_rows = [], []  # open row: [tokens, [texts], {source: tokens}]
    sep_n = 2
    for src, text, n in pieces:
        best = None
        for row in open_rows:
            if row[0] + sep_n + n <= budget and (best is None or row[0] > best[0]):
                best = row
        if best is None:
            if len(open_rows) >= 64:
                full = max(open_rows, key=lambda r: r[0])
                open_rows.remove(full)
                chunks.append((SEP.join(full[1]), full[0], full[2]))
            best = [-sep_n, [], {}]  # first piece adds no separator
            open_rows.append(best)
        best[0] += n + sep_n
        best[1].append(text)
        best[2][src] = best[2].get(src, 0) + n
    chunks.extend((SEP.join(r[1]), r[0], r[2]) for r in open_rows)
    random.Random(args.seed + 1).shuffle(chunks)
    held, train = chunks[:args.heldout_n], chunks[args.heldout_n:]
    for path, rows in ((args.out, train), (args.heldout_out, held)):
        with open(path, 'w', encoding='utf-8') as f:
            for text, _, _ in rows:
                f.write(json.dumps({'text': text}, ensure_ascii=False) + '\n')
    tok_by_src = {}
    for _, _, s in train:
        for k, v in s.items():
            tok_by_src[k] = tok_by_src.get(k, 0) + v
    total = sum(n for _, n, _ in train)
    manifest.update({
        'max_seq_len': args.max_seq_len, 'content_token_budget_per_row': budget,
        'train_rows': len(train), 'heldout_rows': len(held), 'train_tokens': total,
        'mean_tokens_per_row': round(total / len(train), 1), 'row_fill': round(total / len(train) / budget, 3),
        'train_token_share': {k: round(v / total, 3) for k, v in tok_by_src.items()},
        'filters': dict(STATS), 'out': args.out, 'heldout_out': args.heldout_out})
    return manifest


# ---------------- SFT ----------------
_TOK = None


def _init(model_dir):
    global _TOK
    from transformers import AutoTokenizer
    _TOK = AutoTokenizer.from_pretrained(model_dir)


def _n_tokens(convs):
    return len(_TOK(_TOK.apply_chat_template(convs, tokenize=False)).input_ids)


def valid(convs):
    if not convs or convs[-1]['role'] != 'assistant' or not any(m['role'] == 'user' for m in convs):
        return False
    return all(m['role'] in ('system', 'user', 'assistant') and m['content'].strip() for m in convs)


def sft_smoltalk(seed):
    for r in load_dataset('HuggingFaceTB/smol-smoltalk', split='train').shuffle(seed=seed):
        yield 'smol_smoltalk', [{'role': m['role'], 'content': (m['content'] or '')} for m in r['messages']]


def sft_glaive(seed):
    for r in load_dataset('glaiveai/glaive-code-assistant', split='train').shuffle(seed=seed):
        yield 'glaive_code', [{'role': 'user', 'content': r['question'] or ''}, {'role': 'assistant', 'content': r['answer'] or ''}]


def sft_codealpaca(seed):
    for r in load_dataset('sahil2801/CodeAlpaca-20k', split='train').shuffle(seed=seed):
        q = (r['instruction'] or '') + (('\n' + r['input']) if r.get('input') else '')
        yield 'code_alpaca', [{'role': 'user', 'content': q}, {'role': 'assistant', 'content': r['output'] or ''}]


def build_sft(args):
    items, seen, per_src = [], set(), {}
    for gen in (sft_smoltalk(args.seed), sft_glaive(args.seed), sft_codealpaca(args.seed)):
        for src, convs in gen:
            s = per_src.setdefault(src, {'read': 0, 'invalid': 0, 'cjk': 0, 'duplicate': 0, 'too_long': 0, 'kept': 0})
            s['read'] += 1
            text = '\n'.join(m['content'] for m in convs)
            if not valid(convs):
                s['invalid'] += 1
            elif CJK.search(text):
                s['cjk'] += 1
            elif md5(json.dumps(convs, ensure_ascii=False)) in seen:
                s['duplicate'] += 1
            else:
                seen.add(md5(json.dumps(convs, ensure_ascii=False)))
                items.append((src, convs))
    with Pool(args.workers, initializer=_init, initargs=(args.model_dir,)) as pool:
        lengths = pool.map(_n_tokens, [c for _, c in items], chunksize=500)
    kept = []
    for (src, convs), n in zip(items, lengths):
        if n > args.max_tokens:
            per_src[src]['too_long'] += 1
        else:
            per_src[src]['kept'] += 1
            kept.append((src, convs, n))
    random.Random(args.seed).shuffle(kept)
    held, train = kept[:args.heldout_n], kept[args.heldout_n:]
    for path, rows in ((args.out, train), (args.heldout_out, held)):
        with open(path, 'w', encoding='utf-8') as f:
            for _, convs, _ in rows:
                f.write(json.dumps({'conversations': convs}, ensure_ascii=False) + '\n')
    ls = sorted(n for _, _, n in train)
    pct = lambda q: ls[int(q * (len(ls) - 1))]
    train_src = {}
    for s, _, _ in train:
        train_src[s] = train_src.get(s, 0) + 1
    return {'max_tokens': args.max_tokens, 'sources': per_src, 'train_rows': len(train), 'heldout_rows': len(held),
            'train_share': {k: round(v / len(train), 3) for k, v in train_src.items()},
            'template_tokens': {'mean': round(sum(ls) / len(ls), 1), 'p50': pct(.5), 'p90': pct(.9), 'p99': pct(.99), 'max': ls[-1]},
            'out': args.out, 'heldout_out': args.heldout_out}


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--mode', required=True, choices=['pretrain', 'sft'])
    p.add_argument('--out', required=True)
    p.add_argument('--heldout-out', required=True)
    p.add_argument('--manifest', required=True)
    p.add_argument('--tokenizer', default='model/tokenizer.json')
    p.add_argument('--model-dir', default='model')
    p.add_argument('--max-seq-len', type=int, default=768)
    p.add_argument('--max-tokens', type=int, default=740, help='sft: drop conversations longer than this after the chat template')
    p.add_argument('--heldout-n', type=int, default=1000)
    p.add_argument('--cosmopedia', default='dataset/tok_cosmopedia.jsonl')
    p.add_argument('--cosmopedia-mb', type=float, default=400)
    p.add_argument('--tinystories-mb', type=float, default=300)
    p.add_argument('--fineweb-mb', type=float, default=450)
    p.add_argument('--python-mb', type=float, default=450)
    p.add_argument('--workers', type=int, default=18)
    p.add_argument('--seed', type=int, default=0)
    args = p.parse_args()
    manifest = build_pretrain(args) if args.mode == 'pretrain' else build_sft(args)
    json.dump(manifest, open(args.manifest, 'w'), indent=2)
    print(json.dumps(manifest, indent=2), flush=True)
    os._exit(0)  # skip interpreter teardown: the streaming datasets library can abort during shutdown


if __name__ == '__main__':
    main()
